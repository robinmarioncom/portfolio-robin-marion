let lightboxTrigger = null;

function getLightboxFocusableElements(lightbox) {
  return [...lightbox.querySelectorAll("button, [href], input, select, textarea, [tabindex]:not([tabindex='-1'])")]
    .filter((element) => !element.hasAttribute("disabled") && element.getAttribute("aria-hidden") !== "true");
}

function openLightbox(src, alt, trigger) {
  closeLightbox({ restoreFocus: false });
  lightboxTrigger = trigger;

  const overlay = document.createElement("div");
  overlay.className = "lightbox";
  overlay.setAttribute("role", "dialog");
  overlay.setAttribute("aria-modal", "true");
  overlay.innerHTML = `
    <button class="lightbox-close" type="button" aria-label="Fermer l'image agrandie">Fermer</button>
    <img src="${escapeHtml(src)}" alt="${escapeHtml(alt)}">
  `;

  overlay.addEventListener("click", (event) => {
    if (event.target === overlay || event.target.closest(".lightbox-close")) {
      closeLightbox();
    }
  });

  document.body.appendChild(overlay);
  document.body.classList.add("lightbox-open");
  overlay.querySelector(".lightbox-close").focus();
}

function closeLightbox({ restoreFocus = true } = {}) {
  const lightbox = document.querySelector(".lightbox");
  if (!lightbox) return;

  lightbox.remove();
  document.body.classList.remove("lightbox-open");
  if (restoreFocus && lightboxTrigger?.isConnected) {
    lightboxTrigger.focus();
  }
  lightboxTrigger = null;
}

window.addEventListener("keydown", (event) => {
  const lightbox = document.querySelector(".lightbox");
  if (!lightbox) return;

  if (event.key === "Escape") {
    closeLightbox();
    return;
  }

  if (event.key === "Tab") {
    const focusable = getLightboxFocusableElements(lightbox);
    if (!focusable.length) return;

    const first = focusable[0];
    const last = focusable[focusable.length - 1];
    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }
});

let revealObserver;

function enhancePage() {
  const animatedItems = document.querySelectorAll(
    ".project-card, .method-grid article, .media-tile, .fact-list div, .prose-block > div, .side-panel > div, .photo-panel, .contact-panel, .table-wrap"
  );

  if (revealObserver) {
    revealObserver.disconnect();
  }

  if ("IntersectionObserver" in window) {
    revealObserver = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          revealObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.14, rootMargin: "0px 0px -8% 0px" });

    animatedItems.forEach((item, index) => {
      item.classList.add("reveal");
      item.style.setProperty("--reveal-delay", `${Math.min(index * 26, 260)}ms`);
      revealObserver.observe(item);
    });
  } else {
    animatedItems.forEach((item) => item.classList.add("is-visible"));
  }

  bindTiltCards();
  updateChrome();
}

function bindTiltCards(scope = document) {
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  scope.querySelectorAll(".project-card").forEach((card) => {
    card.addEventListener("mousemove", (event) => {
      const rect = card.getBoundingClientRect();
      const x = (event.clientX - rect.left) / rect.width - 0.5;
      const y = (event.clientY - rect.top) / rect.height - 0.5;
      card.style.setProperty("--tilt-x", `${(y * -3).toFixed(2)}deg`);
      card.style.setProperty("--tilt-y", `${(x * 3).toFixed(2)}deg`);
    });

    card.addEventListener("mouseleave", () => {
      card.style.removeProperty("--tilt-x");
      card.style.removeProperty("--tilt-y");
    });
  });
}

function updateChrome() {
  const progress = document.querySelector("[data-scroll-progress]");
  const max = Math.max(document.documentElement.scrollHeight - window.innerHeight, 1);
  const ratio = Math.min(window.scrollY / max, 1);
  document.querySelector("[data-header]")?.classList.toggle("is-scrolled", window.scrollY > 18);
  if (progress) progress.style.transform = `scaleX(${ratio})`;
}

