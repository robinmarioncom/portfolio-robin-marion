function shortText(text, maxLength = 240) {
  const value = String(text || "").replace(/\s+/g, " ").trim();
  if (value.length <= maxLength) return value;
  const sentence = value.slice(0, maxLength + 1).match(/^(.+?[.!?])\s/);
  if (sentence && sentence[1].length > 80) return sentence[1];
  const cut = value.slice(0, maxLength).split(" ").slice(0, -1).join(" ") || value.slice(0, maxLength);
  return `${cut.replace(/[,:;]$/, "")}...`;
}

